#!/usr/bin/env python3
"""
Regenerates app/src/main/res/values*/strings.xml from the Python string tables in this folder.

  en.py        -> values/strings.xml           (source of truth)
  hinglish.py  -> values-b+hi+Latn/strings.xml (Hindi in Latin script)
  bn.py        -> values-bn/strings.xml
  hi.py        -> values-hi/strings.xml
  ja.py        -> values-ja/strings.xml

Each module defines S = {name: text} and P = {name: (one, other)} (or a 1-tuple for languages
without plural forms). Edit the tables, run this script, then run tools/check_resources.py.
Your Friend — Original project by Suvo.
"""
import importlib
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(os.path.dirname(os.path.dirname(HERE)), "app", "src", "main", "res")
sys.path.insert(0, HERE)
LANGS = [("en", "values"), ("hinglish", "values-b+hi+Latn"), ("bn", "values-bn"), ("hi", "values-hi"), ("ja", "values-ja")]
FMT = re.compile(r"%(?:\d+\$)?0?\d*[sd]")


def esc(t):
    t = t.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    t = t.replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n")
    if t.startswith("@") or t.startswith("?"):
        t = "\\" + t
    return t


def write(module, folder):
    m = importlib.import_module(module)
    out = ['<?xml version="1.0" encoding="utf-8"?>',
           '<!-- Generated by tools/i18n/generate.py — edit the .py tables, not this file. Your Friend — Original project by Suvo. -->',
           '<resources>']
    for k in sorted(m.S):
        out.append(f'    <string name="{k}">{esc(m.S[k])}</string>')
    for k in sorted(getattr(m, "P", {})):
        v = m.P[k]
        items = {"one": v[0], "other": v[1]} if len(v) == 2 else {"other": v[0]}
        out.append(f'    <plurals name="{k}">')
        for q, t in items.items():
            out.append(f'        <item quantity="{q}">{esc(t)}</item>')
        out.append('    </plurals>')
    out.append('</resources>')
    os.makedirs(os.path.join(RES, folder), exist_ok=True)
    with open(os.path.join(RES, folder, "strings.xml"), "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    return m


def main():
    en = write(*LANGS[0])
    ok = True
    for module, folder in LANGS[1:]:
        m = write(module, folder)
        for k in sorted(set(m.S) - set(en.S)):
            print(f"{module}: unknown key {k}")
            ok = False
        for k, v in m.S.items():
            if k in en.S and sorted(FMT.findall(v)) != sorted(FMT.findall(en.S[k])):
                print(f"{module}: format mismatch in {k}")
                ok = False
        missing = set(en.S) - set(m.S)
        print(f"{folder}: {len(m.S)}/{len(en.S)} strings" + (f" ({len(missing)} fall back to English)" if missing else ""))
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
