#!/usr/bin/env python3
"""
Writes the launch-screen colours and styles for every accent preset, from the same maths as
ui/Palette.java (background role, light and dark). Run after changing Palette.SEEDS:
    python3 tools/theme/gen_splash.py
"""
import colorsys
import os
import re

ROOT = os.path.join(os.path.dirname(__file__), "..", "..", "app", "src", "main")
PALETTE = os.path.join(ROOT, "java", "com", "suvo", "agent", "ui", "Palette.java")
LIGHT_BG = (-17.7, 1.000, 0.975)
DARK_BG = (-5.4, 0.353, 0.067)


def seeds():
    src = open(PALETTE).read()
    m = re.search(r"String\[\] SEEDS = \{([^}]*)\}", src)
    return re.findall(r'"(#[0-9A-Fa-f]{6})"', m.group(1))


def hsl_of(hexc):
    r, g, b = (int(hexc[i:i + 2], 16) / 255 for i in (1, 3, 5))
    h, l, s = colorsys.rgb_to_hls(r, g, b)
    return h * 360, s, l


def chroma(sat):
    # Same rule as Palette.chromaFor: only greyish seeds (brown, blue grey) are toned down.
    return 1.0 if sat >= 0.4 else max(0.15, sat / 0.4)


def role(hue, f, r):
    h = ((hue + r[0]) % 360 + 360) % 360
    rr, gg, bb = colorsys.hls_to_rgb(h / 360, r[2], r[1] * f)
    return "#%02X%02X%02X" % (round(rr * 255), round(gg * 255), round(bb * 255))


def main():
    ss = seeds()
    light, dark = [], []
    for s in ss:
        h, sat, _ = hsl_of(s)
        f = chroma(sat)
        light.append(role(h, f, LIGHT_BG))
        dark.append(role(h, f, DARK_BG))
    for folder, cols, label in (("values", light, "light"), ("values-night", dark, "dark")):
        p = os.path.join(ROOT, "res", folder, "splash_colors.xml")
        text = open(p).read()
        keep = re.search(r'\s*<!-- The app name.*?</color>', text, re.S)
        body = "".join('    <color name="splash_s%d">%s</color>\n' % (i, c) for i, c in enumerate(cols))
        out = ('<?xml version="1.0" encoding="utf-8"?>\n<resources>\n    <!-- Launch screen backgrounds, %s. '
               'Generated by tools/theme/gen_splash.py from Palette (background role) for each accent. -->\n%s'
               % (label, body))
        out += (keep.group(0).rstrip() + "\n" if keep else "") + "</resources>\n"
        open(p, "w").write(out)
    p = os.path.join(ROOT, "res", "values-v31", "splash.xml")
    text = open(p).read()
    head = text[:text.index("    <style name=\"Theme.YourFriend.Splash.S0\"")]
    tail = text[text.index("    <style name=\"Theme.YourFriend.Splash.Dynamic\""):]
    styles = "".join(
        '    <style name="Theme.YourFriend.Splash.S%d" parent="Theme.YourFriend">\n'
        '        <item name="android:windowSplashScreenBackground">@color/splash_s%d</item>\n'
        '        <item name="android:windowSplashScreenAnimatedIcon">@drawable/splash_name</item>\n'
        '        <item name="android:windowSplashScreenIconBackgroundColor">@android:color/transparent</item>\n'
        '    </style>\n' % (i, i) for i in range(len(ss)))
    open(p, "w").write(head + styles + tail)
    print(len(ss), "accents")


if __name__ == "__main__":
    main()
